"""Reads the panel outlines drawn in Illustrator (public/calculator/<body>-side.svg and <body>-top.svg,
1600 x 640, one closed shape per panel named with its panel id) into data/calculator-geometry.ts.
Usage: python scripts/import_outlines.py

- side view: the car's left side; side panels get "-st" (the right side is the photo mirrored)
- top view: the car seen from above, front to the left; a side panel is "-dr" in the upper half
  and "-st" in the lower half, whatever number Illustrator put after it ("usa-fata-2")
- shapes of one panel (several paths, or a group) are joined into one outline
- the window line ("belt") of the side views is kept from the previous geometry file
A body whose SVG is missing or has unnamed shapes keeps its previous outlines for that view."""
import json, re, sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PHOTOS = ROOT / "public" / "calculator"
OUT = ROOT / "data" / "calculator-geometry.ts"
BODIES = ["hatchback", "sedan", "break", "suv", "utilitara"]
SHARED = {"bara-fata", "bara-spate", "capota", "plafon", "portbagaj", "panou-frontal", "usi-spate"}
RENAME = {"plafion": "plafon", "haion": "plafon"}      # typos and pieces counted with another one
# the van's top view names its pieces after where they sit; the same pieces as on the side view
RENAME_BODY = {"utilitara": {"panou-fata": "usa-culisanta", "panou-spate": "panou-lateral", "portbagaj": "usi-spate"}}
NS = "{http://www.w3.org/2000/svg}"

def path_of(el):
    tag = el.tag.replace(NS, "")
    if tag == "path":
        return el.get("d", "")
    if tag in ("polygon", "polyline"):
        pts = el.get("points", "").split()
        return "M" + " L".join(pts) + ("Z" if tag == "polygon" else "")
    if tag == "rect":
        x, y, w, h = (float(el.get(k, 0)) for k in ("x", "y", "width", "height"))
        return f"M{x},{y} h{w} v{h} h{-w}Z"
    return "".join(path_of(c) for c in el)                 # a group

def first_point(d):
    m = re.match(r"\s*[Mm]\s*(-?[\d.]+)[ ,]*(-?[\d.]+)", d)
    return (float(m.group(1)), float(m.group(2))) if m else (0.0, 0.0)

def ys_of(d):
    # every absolute-looking y in the path is enough to tell the upper half from the lower one
    nums = [float(v) for v in re.findall(r"-?\d*\.?\d+", d)]
    return nums[1::2]

def read(body, view):
    f = PHOTOS / f"{body}-{view}.svg"
    if not f.exists():
        return None
    root = ET.parse(f).getroot()
    shapes = [el for el in root.iter() if el.get("id") and el.get("id") != "Layer_1" and el.tag.replace(NS, "") in ("path", "polygon", "polyline", "rect", "g")]
    if not shapes:
        print(f"  {body}-{view}: no named shapes, kept as before")
        return None
    panels = {}
    for el in shapes:
        name = (el.get("data-name") or el.get("id")).strip().lower()
        kind = re.sub(r"[-_ ]?\d+$", "", name)
        kind = RENAME.get(kind, kind)
        kind = RENAME_BODY.get(body, {}).get(kind, kind)
        d = path_of(el)
        if view == "side":
            pid = kind if kind in SHARED else f"{kind}-st"
        elif kind in SHARED:
            pid = kind
        else:
            # the upper half of the top view is the car's right side; the start point is on the
            # outline, so it tells the side
            pid = f"{kind}-{'dr' if first_point(d)[1] < 320 else 'st'}"
        panels[pid] = panels.get(pid, "") + d
    return [[k, v] for k, v in panels.items()]

text = OUT.read_text(encoding="utf8")
geo = json.loads(re.search(r"export const geometry = (\{.*\}) as const", text, re.S).group(1))
for body in BODIES:
    for view in ("side", "top"):
        panels = read(body, view)
        if panels is None:
            continue
        geo.setdefault(body, {}).setdefault(view, {})["panels"] = panels
        print(f"  {body}-{view}: {', '.join(p[0] for p in panels)}")
        geo[body][view]["drawn"] = True
OUT.write_text(
    "// GENERATED by scripts/import_outlines.py from the outlines drawn in Illustrator\n"
    "// (public/calculator/<body>-side.svg / -top.svg). Do not edit by hand.\n"
    "export const geometry = " + json.dumps(geo, ensure_ascii=False) + " as const\n",
    encoding="utf8",
)
